import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const output = path.resolve('test-results');
await mkdir(output, { recursive: true });
const executablePath = process.env.BMFONT_TEST_APP;
const application = await electron.launch({ executablePath, args: executablePath ? [] : ['.'], env: { ...process.env, BMFONT_DEV: '' } });
const errors = [];
try {
  const page = await application.firstWindow();
  const roles = await application.evaluate(({ Menu }) => {
    const collect = menu => menu.items.flatMap(item => [item.role, ...(item.submenu ? collect(item.submenu) : [])]);
    return collect(Menu.getApplicationMenu());
  });
  assert.equal(roles.includes('reload'), false, 'production menu must protect unsaved work from unguarded reload');
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.getByRole('heading', { name: '把字符图片，变成字体。' }).waitFor();
  await page.screenshot({ path: path.join(output, 'empty.png') });
  await application.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1, checkboxChecked: false }); });
  await page.getByRole('button', { name: /先看看 sample/ }).click();
  await page.locator('canvas[data-ready="true"]').waitFor();
  assert.equal(await page.locator('.glyph-row').count(), 13);
  assert.equal(await page.getByRole('spinbutton', { name: '行高', exact: true }).inputValue(), '32');
  await page.getByRole('spinbutton', { name: 'X 偏移', exact: true }).fill('-5');
  await page.getByRole('spinbutton', { name: '行高', exact: true }).fill('96');
  await page.getByRole('tab', { name: '文字预览', exact: true }).click();
  await page.getByRole('textbox', { name: '预览文字', exact: true }).fill('+100x2\n-57');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  assert.notEqual(await page.getByRole('textbox', { name: '预览文字', exact: true }).inputValue(), '+100x2\n-57');
  await page.getByRole('button', { name: '重做', exact: true }).click();
  assert.equal(await page.getByRole('textbox', { name: '预览文字', exact: true }).inputValue(), '+100x2\n-57');
  await page.locator('canvas[data-ready="true"]').waitFor();
  await page.screenshot({ path: path.join(output, 'text-preview.png') });
  const projectFile = path.join(output, 'example.bmfont');
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, projectFile);
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('status').getByText('工程已保存', { exact: false }).waitFor();
  const saved = JSON.parse(await readFile(projectFile, 'utf8'));
  assert.equal(saved.glyphs[0].xoffset, -5);
  assert.equal(saved.previewText, '+100x2\n-57');
  const fontFile = path.join(output, 'example.fnt');
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, fontFile);
  await page.getByRole('button', { name: '导出字体', exact: true }).click();
  await page.getByRole('status').getByText('已导出', { exact: false }).waitFor();
  const fnt = await readFile(fontFile, 'utf8'); assert.match(fnt, /common lineHeight=96/); assert.match(fnt, /xoffset=-5/);
  const meta = await sharp(path.join(output, 'example.png')).metadata(); assert.ok(meta.width > 0 && meta.hasAlpha);
  await page.getByRole('button', { name: '添加空格字符', exact: true }).click();
  assert.equal(await page.locator('.glyph-row').count(), 14);
  await application.evaluate(({ dialog }, file) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] });
    dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false });
  }, projectFile);
  await page.getByRole('button', { name: '打开', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('[inert]'));
  assert.equal(await page.locator('.glyph-row').count(), 14, 'cancel protects unsaved edits');
  await application.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1, checkboxChecked: false }); });
  await page.getByRole('button', { name: '打开', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.glyph-row').length === 13);
  assert.equal(await page.getByRole('spinbutton', { name: 'X 偏移', exact: true }).inputValue(), '-5');
  await page.locator('canvas[data-ready="true"]').waitFor();
  await page.screenshot({ path: path.join(output, 'editor.png') });
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1080, 720));
  await page.waitForFunction(() => window.innerWidth === 1080);
  await page.waitForFunction(() => document.querySelector('.canvas-caption span')?.textContent !== '100%');
  await page.locator('canvas[data-ready="true"]').waitFor();
  assert.equal(await page.locator('.canvas-scroller').evaluate(el => el.scrollHeight <= el.clientHeight + 1 && el.scrollWidth <= el.clientWidth + 1), true, 'fit zoom must fit within the canvas viewport');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true, 'minimum window width has no horizontal overflow');
  await page.screenshot({ path: path.join(output, 'compact.png') });
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 920));

  const input = path.join(output, 'input'); await mkdir(input, { recursive: true });
  await sharp('sample/bonusGold.png').extract({ left: 148, top: 0, width: 73, height: 90 }).png().toFile(path.join(input, '0.png'));
  await sharp('sample/bonusGold.png').extract({ left: 0, top: 0, width: 73, height: 90 }).png().toFile(path.join(input, 'plus.png'));
  await sharp('sample/bonusGold.png').extract({ left: 222, top: 0, width: 73, height: 90 }).png().toFile(path.join(input, 'unknown.png'));
  await application.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, input);
  await page.getByRole('button', { name: '导入目录', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.glyph-row').length === 3);
  assert.equal(await page.getByRole('button', { name: '导出字体', exact: true }).isDisabled(), true);
  await page.locator('.glyph-row').filter({ hasText: 'unknown.png' }).click();
  const mapping = page.getByRole('textbox', { name: '映射字符', exact: true });
  await mapping.fill('U+0031'); await mapping.blur();
  await page.locator('canvas[data-ready="true"]').waitFor();
  assert.equal(await mapping.inputValue(), 'U+0031');
  assert.equal(await page.getByRole('button', { name: '导出字体', exact: true }).isEnabled(), true);
  await page.locator('.glyph-row').filter({ hasText: '0.png' }).click();
  assert.equal(await page.getByRole('textbox', { name: '映射字符', exact: true }).inputValue(), '0');
  await page.getByLabel('裁切透明边缘', { exact: true }).check();
  await page.getByLabel('图集尺寸为 2 的幂', { exact: true }).uncheck();
  const mapped = path.join(output, 'from-directory.fnt');
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, mapped);
  await page.getByRole('button', { name: '导出字体', exact: true }).click();
  await page.getByRole('status').getByText('已导出', { exact: false }).waitFor();
  const directoryFont = await readFile(mapped, 'utf8'); assert.match(directoryFont, /char id=48 /); assert.match(directoryFont, /char id=49 /); assert.match(directoryFont, /char id=43 /);
  await page.getByLabel('描述文件格式', { exact: true }).selectOption('xml');
  const xml = path.join(output, 'from-directory-xml.fnt');
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, xml);
  await page.getByRole('button', { name: '导出字体', exact: true }).click();
  await page.getByRole('status').getByText('已导出', { exact: false }).waitFor();
  assert.match(await readFile(xml, 'utf8'), /<chars count="3">/);
  await page.screenshot({ path: path.join(output, 'directory-import.png') });
  assert.deepEqual(errors, [], 'renderer has no runtime errors');
  console.log('PASS: sample, metrics, bitmap preview, project save/reopen, discard guard, directory import, manual Unicode mapping, trimmed PNG/text/XML export.');
} catch (error) {
  const page = await application.firstWindow().catch(() => null);
  if (page) { await page.screenshot({ path: path.join(output, 'failure.png') }); console.error((await page.locator('body').innerText()).slice(-3000)); }
  throw error;
} finally { await application.close(); }
